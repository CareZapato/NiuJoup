export type IconName = keyof typeof ICONS;

const TECHNIQUE_ICON: Record<string, IconName> = {
  kamehameha: 'beam',
  kaioken: 'kaioken',
  teleport: 'teleport',
  kienzan: 'disc',
  taiyoken: 'sun',
  kakusandan: 'scatter',
  rogafufuken: 'wolf',
  sokidan: 'orb',
  ki_volley: 'limit',
  renzoku_kienzan: 'limit',
  shin_rogafufuken: 'limit',
};

export function techniqueIcon(moveId: string | null): IconName | null {
  if (!moveId) return null;
  return TECHNIQUE_ICON[moveId] ?? 'blast';
}

function runs(rows: readonly string[]): { x: number; y: number; w: number; accent: boolean }[] {
  const out: { x: number; y: number; w: number; accent: boolean }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') {
        x++;
        continue;
      }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      out.push({ x, y, w, accent: ch === '+' });
      x += w;
    }
  });
  return out;
}

const RUNS = Object.fromEntries(Object.entries(ICONS).map(([k, v]) => [k, runs(v)])) as Record<IconName, ReturnType<typeof runs>>;

/** Integer cell size keeps the art crisp at any button size. */
export const PixelIcon = memo(function PixelIcon({ name, size, color, accent }: { name: IconName; size: number; color: string; accent: string }) {
  const cell = Math.max(1, Math.floor(size / 12));
  const dim = cell * 12;
  const parts = useMemo(() => RUNS[name], [name]);
  return (
    <View style={{ width: dim, height: dim }} pointerEvents="none">
      {parts.map((r, i) => (
        <View key={i} style={{ position: 'absolute', left: r.x * cell, top: r.y * cell, width: r.w * cell, height: cell, backgroundColor: r.accent ? accent : color }} />
      ))}
    </View>
  );
});

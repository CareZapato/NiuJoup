export function getMove(id: string): MoveDef {
  const m = MOVES[id];
  if (!m) throw new Error(`Unknown move ${id}`);
  return m;
}

export const moveTotalTicks = (m: MoveDef): number => m.startup + m.active + m.recovery;

export const isTechnique = (id: string): boolean => !!MOVES[id]?.technique;

/** Every sequence (primary and alternative) a technique accepts. */
export function sequencesOf(m: MoveDef): { sequence: string[]; mode: 'spread' | 'concentrate' }[] {
  const t = m.technique;
  if (!t?.sequence) return [];
  const out: { sequence: string[]; mode: 'spread' | 'concentrate' }[] = [{ sequence: t.sequence, mode: 'spread' }];
  if (t.altSequence) out.push({ sequence: t.altSequence.sequence, mode: 'concentrate' });
  return out;
}

